-- One-time governance setup for CLINICAL_CLAIMS_DV (run before dbt build).
-- Part 1 needs ACCOUNTADMIN; part 2 runs as ATTENDEE_ROLE (owner of the database).

------------------------------------------------------------------
-- Part 1: account-level grants (ACCOUNTADMIN)
------------------------------------------------------------------
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS PHI_READER COMMENT = 'Sees PII/PHI columns unmasked in CLINICAL_CLAIMS_DV';
CREATE ROLE IF NOT EXISTS PARTNER_ANALYST COMMENT = 'Clean room partner: aggregate-only access to CLINICAL_CLAIMS_DV.CLEANROOM';
GRANT ROLE PHI_READER TO USER "USER";
GRANT ROLE PARTNER_ANALYST TO USER "USER";
GRANT ROLE PHI_READER TO ROLE ACCOUNTADMIN;
GRANT ROLE PARTNER_ANALYST TO ROLE ACCOUNTADMIN;

GRANT APPLY MASKING POLICY     ON ACCOUNT TO ROLE ATTENDEE_ROLE;
GRANT APPLY AGGREGATION POLICY ON ACCOUNT TO ROLE ATTENDEE_ROLE;
GRANT APPLY PROJECTION POLICY  ON ACCOUNT TO ROLE ATTENDEE_ROLE;
GRANT APPLY TAG                ON ACCOUNT TO ROLE ATTENDEE_ROLE;
GRANT EXECUTE DATA METRIC FUNCTION ON ACCOUNT TO ROLE ATTENDEE_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.DATA_METRIC_USER TO ROLE ATTENDEE_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.CLASSIFICATION_ADMIN TO ROLE ATTENDEE_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.GOVERNANCE_VIEWER TO ROLE ATTENDEE_ROLE;

GRANT USAGE ON WAREHOUSE DEFAULT_WH TO ROLE PHI_READER;
GRANT USAGE ON WAREHOUSE DEFAULT_WH TO ROLE PARTNER_ANALYST;

------------------------------------------------------------------
-- Part 2: tags and tag-based masking (ATTENDEE_ROLE)
------------------------------------------------------------------
USE ROLE ATTENDEE_ROLE;

CREATE SCHEMA IF NOT EXISTS CLINICAL_CLAIMS_DV.GOVERNANCE COMMENT = 'Tags, masking/aggregation/projection policies';
CREATE SCHEMA IF NOT EXISTS CLINICAL_CLAIMS_DV.MARTS      COMMENT = 'Star-schema marts for analytics and the Cortex Agent';
CREATE SCHEMA IF NOT EXISTS CLINICAL_CLAIMS_DV.CLEANROOM  COMMENT = 'Privacy-safe views shared with partners (aggregate-only)';

CREATE TAG IF NOT EXISTS CLINICAL_CLAIMS_DV.GOVERNANCE.DATA_LAYER
  ALLOWED_VALUES 'staging', 'raw_vault', 'business_vault', 'marts', 'cleanroom'
  COMMENT = 'Medallion / Data Vault layer the object belongs to';
CREATE TAG IF NOT EXISTS CLINICAL_CLAIMS_DV.GOVERNANCE.DATA_DOMAIN
  ALLOWED_VALUES 'member', 'provider', 'claims', 'clinical', 'reference'
  COMMENT = 'Business domain';
CREATE TAG IF NOT EXISTS CLINICAL_CLAIMS_DV.GOVERNANCE.DATA_OWNER
  COMMENT = 'Accountable owning team';
CREATE TAG IF NOT EXISTS CLINICAL_CLAIMS_DV.GOVERNANCE.SENSITIVITY
  ALLOWED_VALUES 'PII', 'PHI', 'QUASI_IDENTIFIER', 'INTERNAL'
  COMMENT = 'Column sensitivity. PII/PHI values are masked unless PHI_READER is in session';

-- Single source of truth for who sees clear text
CREATE OR REPLACE FUNCTION CLINICAL_CLAIMS_DV.GOVERNANCE.UNMASK_PHI()
RETURNS BOOLEAN
MEMOIZABLE
AS $$ IS_ROLE_IN_SESSION('PHI_READER') OR IS_ROLE_IN_SESSION('ACCOUNTADMIN') $$;

CREATE OR REPLACE MASKING POLICY CLINICAL_CLAIMS_DV.GOVERNANCE.MASK_STRING_SENSITIVE AS (val VARCHAR) RETURNS VARCHAR ->
  CASE
    WHEN SYSTEM$GET_TAG_ON_CURRENT_COLUMN('CLINICAL_CLAIMS_DV.GOVERNANCE.SENSITIVITY') NOT IN ('PII', 'PHI') THEN val
    WHEN CLINICAL_CLAIMS_DV.GOVERNANCE.UNMASK_PHI() THEN val
    ELSE '***MASKED***'
  END
  COMMENT = 'Masks text columns tagged SENSITIVITY = PII/PHI';

CREATE OR REPLACE MASKING POLICY CLINICAL_CLAIMS_DV.GOVERNANCE.MASK_NUMBER_SENSITIVE AS (val NUMBER) RETURNS NUMBER ->
  CASE
    WHEN SYSTEM$GET_TAG_ON_CURRENT_COLUMN('CLINICAL_CLAIMS_DV.GOVERNANCE.SENSITIVITY') NOT IN ('PII', 'PHI') THEN val
    WHEN CLINICAL_CLAIMS_DV.GOVERNANCE.UNMASK_PHI() THEN val
    ELSE NULL
  END
  COMMENT = 'Masks numeric columns (ZIP, lat/lon) tagged SENSITIVITY = PII/PHI';

CREATE OR REPLACE MASKING POLICY CLINICAL_CLAIMS_DV.GOVERNANCE.MASK_DATE_SENSITIVE AS (val DATE) RETURNS DATE ->
  CASE
    WHEN SYSTEM$GET_TAG_ON_CURRENT_COLUMN('CLINICAL_CLAIMS_DV.GOVERNANCE.SENSITIVITY') NOT IN ('PII', 'PHI') THEN val
    WHEN CLINICAL_CLAIMS_DV.GOVERNANCE.UNMASK_PHI() THEN val
    ELSE DATE_TRUNC('year', val)
  END
  COMMENT = 'Generalises dates tagged SENSITIVITY = PII/PHI to the year';

ALTER TAG CLINICAL_CLAIMS_DV.GOVERNANCE.SENSITIVITY SET
  MASKING POLICY CLINICAL_CLAIMS_DV.GOVERNANCE.MASK_STRING_SENSITIVE,
  MASKING POLICY CLINICAL_CLAIMS_DV.GOVERNANCE.MASK_NUMBER_SENSITIVE,
  MASKING POLICY CLINICAL_CLAIMS_DV.GOVERNANCE.MASK_DATE_SENSITIVE;

-- Let the unmasked role read the governed layers
GRANT USAGE ON DATABASE CLINICAL_CLAIMS_DV TO ROLE PHI_READER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE CLINICAL_CLAIMS_DV TO ROLE PHI_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA CLINICAL_CLAIMS_DV.MARTS TO ROLE PHI_READER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA CLINICAL_CLAIMS_DV.MARTS TO ROLE PHI_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA CLINICAL_CLAIMS_DV.RAW_VAULT TO ROLE PHI_READER;
