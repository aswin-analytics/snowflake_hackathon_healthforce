"""Generate models/raw_vault/_raw_vault.yml (descriptions, domain meta, column sensitivity, tests)
from the hub/link/sat model files, so docs and Horizon tags stay in sync with the vault."""
import os, re
ROOT = os.path.join(os.path.dirname(__file__), "..", "models", "raw_vault")
DOMAIN = {"patient": "member", "payer_transition": "member", "payer": "reference", "provider": "provider",
          "organization": "provider", "claim": "claims", "claim_tx": "claims"}
NICE = {"patient": "patient (member)", "claim_tx": "claim transaction (charge/payment line)",
        "payer_transition": "patient insurance enrolment period"}
PII_SENS = {"SSN": "PII", "DRIVERS": "PII", "PASSPORT": "PII", "FIRST": "PII", "MIDDLE": "PII", "LAST": "PII",
            "MAIDEN": "PII", "ADDRESS": "PII", "ZIP": "QUASI_IDENTIFIER", "LAT": "PII", "LON": "PII"}
DETAIL_SENS = {"BIRTHDATE": "PHI", "DEATHDATE": "PHI", "BIRTHPLACE": "QUASI_IDENTIFIER"}

def sets(path):
    txt = open(path).read()
    return dict(re.findall(r'set (\w+) = (.+?) -%}', txt))

L = ["# Generated by scripts/gen_raw_vault_yml.py - edit the script, not this file.", "version: 2", "", "models:"]
def model(name, desc, domain, cols, pii=False, dmfs=None, col_dmfs=None):
    col_dmfs = col_dmfs or {}
    tags = ["'domain:" + domain + "'"] + (["'pii'"] if pii else [])
    L.extend([f"  - name: {name}", f"    description: \"{desc}\"", "    config:",
              f"      tags: [{', '.join(tags)}]", "      meta:", f"        data_domain: {domain}"])
    if dmfs: L.append(f"        dmfs: [{', '.join(dmfs)}]")
    L.append("    columns:")
    for c, d, tests, sens in cols:
        L.append(f"      - name: {c}")
        if d: L.append(f"        description: \"{d}\"")
        meta = []
        if sens: meta.append(f"          sensitivity: {sens}")
        if c in col_dmfs: meta.append(f"          dmfs: [{', '.join(col_dmfs[c])}]")
        if meta: L.extend(["        meta:"] + meta)
        if tests: L.append(f"        data_tests: [{', '.join(tests)}]")

for f in sorted(os.listdir(f"{ROOT}/hubs")):
    s = sets(f"{ROOT}/hubs/{f}"); e = f[4:-4]
    pk, nk, src = s["src_pk"].strip('"'), s["src_nk"].strip('"'), s["source_model"].strip('"')
    model(f[:-4], f"Hub: one row per unique {NICE.get(e, e.replace('_', ' '))}, keyed by the MD5 hash of {nk} (from {src}).",
          DOMAIN.get(e, "clinical"),
          [(pk, f"Hash key = MD5 of {nk}", ["unique", "not_null"], None),
           (nk, "Source business key", ["not_null"], None),
           ("LOAD_DATETIME", "When the key was first loaded", [], None),
           ("RECORD_SOURCE", "Source system and table", [], None)],
          dmfs=["ROW_COUNT", "FRESHNESS"],
          col_dmfs={nk: ["NULL_COUNT", "DUPLICATE_COUNT"]})

for f in sorted(os.listdir(f"{ROOT}/links")):
    s = sets(f"{ROOT}/links/{f}")
    pk = s["src_pk"].strip('"'); fks = re.findall(r'"(\w+)"', s["src_fk"])
    e = fks[0][:-3].lower()
    model(f[:-4], "Link: relationship between " + ", ".join(k[:-3].lower() for k in fks) + ".", DOMAIN.get(e, "clinical"),
          [(pk, "Hash of the combined business keys", ["unique", "not_null"], None)] +
          [(k, f"Hash key of hub_{k[:-3].lower()}", ["not_null"], None) for k in fks])

for f in sorted(os.listdir(f"{ROOT}/sats")):
    s = sets(f"{ROOT}/sats/{f}"); name = f[:-4]
    pk = s["src_pk"].strip('"'); e = pk[:-3].lower(); payload = re.findall(r'"(\w+)"', s["src_payload"])
    is_pii = name.endswith("_pii")
    cols = [(pk, "Parent hub hash key", ["not_null"], None),
            (s["src_hashdiff"].strip('"'), "MD5 of the payload; a new row is inserted only when it changes", [], None)]
    sens_map = PII_SENS if is_pii else (DETAIL_SENS if e == "patient" else {})
    cols += [(c, None, [], sens_map[c]) for c in payload if c in sens_map]
    desc = ("Satellite: patient direct identifiers (PII), isolated for masking and access control." if is_pii else
            f"Satellite: descriptive attributes of {NICE.get(e, e.replace('_', ' '))} with change history.")
    model(name, desc, DOMAIN.get(e, "clinical"), cols, pii=(e == "patient"))

open(f"{ROOT}/_raw_vault.yml", "w").write("\n".join(L) + "\n")
print("models:", sum(1 for x in L if x.startswith("  - name:")))
